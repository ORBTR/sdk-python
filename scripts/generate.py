#!/usr/bin/env python3
"""Generates src/orbtr/_generated/types.py and resources.py from contract/orbtr-v1.json.

Consumes the contract's components.schemas and its paths' x-orbtr-* operation fields. A schema reachable from
a request body is generated as a TypedDict (the caller builds it); one reachable from a response or a stream
is generated as a dataclass with from_dict. The output is imported by src/orbtr/_client.py and
src/orbtr/types.py; tests/test_generated.py regenerates in memory and fails when the files differ.

Usage: python3 scripts/generate.py [--check]
"""

from __future__ import annotations

import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by scripts/generate.py from contract/orbtr-v1.json. Do not edit.\n"


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()
    if keyword.iskeyword(s) or not s.isidentifier():
        s += "_"
    return s


def pascal(s: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[._]", s))


def refs_in(schema: dict) -> list[str]:
    out = []
    if "$ref" in schema:
        out.append(ref_name(schema["$ref"]))
    for key in ("items",):
        if key in schema:
            out += refs_in(schema[key])
    for sub in schema.get("oneOf", []):
        out += refs_in(sub)
    for p in schema.get("properties", {}).values():
        out += refs_in(p)
    return out


def operations(contract: dict) -> list[dict]:
    ops = []
    for path, item in contract["paths"].items():
        for method, op in item.items():
            content = op["responses"]["200"]["content"]
            ctype = next(iter(content))
            body = op.get("requestBody")
            ops.append({
                "path": path,
                "http": method.upper(),
                "resource": op["x-orbtr-resource"],
                "name": op["x-orbtr-method"],
                "summary": op["summary"],
                "scope": op["x-orbtr-scope"],
                "idempotent": op.get("x-orbtr-idempotency-key") is True,
                "stream": op.get("x-orbtr-stream"),
                "body": ref_name(body["content"]["application/json"]["schema"]["$ref"]) if body else None,
                "response": ref_name(content[ctype]["schema"]["$ref"]),
                "ndjson": ctype == "application/x-ndjson",
                "path_params": [p for p in op.get("parameters", []) if p["in"] == "path"],
                "query_params": [p for p in op.get("parameters", []) if p["in"] == "query"],
            })
    return ops


def classify(contract: dict) -> tuple[set[str], set[str]]:
    schemas = contract["components"]["schemas"]

    def closure(start: list[str]) -> set[str]:
        seen: set[str] = set()
        todo = list(start)
        while todo:
            n = todo.pop()
            if n in seen:
                continue
            seen.add(n)
            todo += refs_in(schemas[n])
        return seen

    ops = operations(contract)
    req = closure([o["body"] for o in ops if o["body"]])
    resp = closure([o["response"] for o in ops] + [ref_name(o["stream"]["event"]) for o in ops if o["stream"]])
    both = req & resp
    if both:
        raise SystemExit(f"schemas used by both requests and responses: {sorted(both)}")
    return req, resp


def py_type(s: dict, sequence: bool = False) -> str:
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "oneOf" in s:
        return " | ".join(py_type(x, sequence) for x in s["oneOf"])
    types = s["type"] if isinstance(s["type"], list) else [s["type"]]
    parts = []
    for t in types:
        if t == "string":
            parts.append("Literal[" + ", ".join(json.dumps(e) for e in s["enum"]) + "]" if "enum" in s else "str")
        elif t == "integer":
            parts.append("int")
        elif t == "number":
            parts.append("float")
        elif t == "boolean":
            parts.append("bool")
        elif t == "null":
            parts.append("None")
        elif t == "array":
            parts.append(("Sequence[" if sequence else "list[") + py_type(s["items"], sequence) + "]")
        elif t == "object":
            if "properties" in s:
                raise SystemExit("inline object schemas are not supported")
            parts.append("dict[str, Any]")
        else:
            raise SystemExit(f"unsupported type {t}")
    return " | ".join(parts)


def doc_lines(text: str, indent: str) -> str:
    return f'{indent}"""{text}"""\n'


def describe(ps: dict, schemas: dict) -> str:
    if "description" in ps:
        return ps["description"]
    if "$ref" in ps:
        return schemas[ref_name(ps["$ref"])]["description"]
    return ""


def parse_expr(s: dict, v: str, schemas: dict) -> str:
    if "$ref" in s:
        name = ref_name(s["$ref"])
        target = schemas[name]
        fn = f"parse_{snake(name)}" if "oneOf" in target else f"{name}.from_dict"
        return f"parse_obj({v}, {fn})"
    t = s.get("type")
    if t == "array":
        items = s["items"]
        if "$ref" in items:
            name = ref_name(items["$ref"])
            fn = f"parse_{snake(name)}" if "oneOf" in schemas[name] else f"{name}.from_dict"
            return f"parse_list({v}, {fn})"
        return f"parse_list({v}, None)"
    return v


def gen_types(contract: dict) -> str:
    schemas = contract["components"]["schemas"]
    req, resp = classify(contract)
    names = []
    body = ""
    for name, s in schemas.items():
        if name in ("ResponseModel", "extra_keys", "parse_list", "parse_obj"):
            raise SystemExit(f"{name} collides with a name the generated types import")
        if name not in req and name not in resp:
            raise SystemExit(f"{name} is used by no operation")
        names.append(name)
        if "oneOf" in s:
            disc = s.get("discriminator")
            if not disc or name in req:
                raise SystemExit(f"{name}: only discriminated response unions are supported at the top level")
            members = [ref_name(x["$ref"]) for x in s["oneOf"]]
            body += f"{name} = Union[{', '.join(members)}]\n"
            body += doc_lines(s["description"], "")
            body += "\n"
            table = f"_{snake(name).upper()}_TYPES"
            body += f"{table}: dict[str, Any] = {{\n"
            for value, target in disc["mapping"].items():
                body += f"    {json.dumps(value)}: {ref_name(target)},\n"
            body += "}\n\n\n"
            body += f"def parse_{snake(name)}(data: dict[str, Any]) -> {name}:\n"
            body += f'    """Reads one {name} by its {disc["propertyName"]}."""\n'
            body += f"    cls = {table}.get(data.get({json.dumps(disc['propertyName'])}))\n"
            body += "    if cls is None:\n"
            body += f"        raise ValueError(f\"not a {name}: {{data.get('{disc['propertyName']}')!r}}\")\n"
            body += "    return cls.from_dict(data)\n\n\n"
            names.append(f"parse_{snake(name)}")
            continue
        required = set(s.get("required", []))
        props = s["properties"]
        if name in req:
            body += f"class {name}(TypedDict, total=False):\n"
            body += doc_lines(s["description"], "    ")
            for p, ps in props.items():
                if not p.isidentifier() or keyword.iskeyword(p):
                    raise SystemExit(f"{name}.{p} is not a Python identifier")
                t = py_type(ps)
                body += f"\n    {p}: {'Required[' + t + ']' if p in required else t}\n"
                body += doc_lines(describe(ps, schemas), "    ")
            body += "\n\n"
            continue
        body += "@dataclass(kw_only=True)\n"
        body += f"class {name}(ResponseModel):\n"
        body += doc_lines(s["description"], "    ")
        args = []
        for p, ps in props.items():
            attr = snake(p)
            if attr == "extra":
                raise SystemExit(f"{name}.{p} collides with the extra attribute")
            t = py_type(ps)
            nullable = isinstance(ps.get("type"), list) and "null" in ps["type"]
            meta = f'metadata={{"json": {json.dumps(p)}}}' if attr != p else ""
            if p in required:
                default = f" = field({meta})" if meta else ""
            else:
                if not nullable:
                    t += " | None"
                default = f" = field(default=None, {meta})" if meta else " = None"
            body += f"\n    {attr}: {t}{default}\n"
            body += doc_lines(describe(ps, schemas), "    ")
            args.append(f"            {attr}={parse_expr(ps, f'data.get({json.dumps(p)})', schemas)},")
        body += "\n    extra: dict[str, Any] = field(default_factory=dict, repr=False, compare=False)\n"
        body += '    """Fields the response carried that this version of the SDK does not know."""\n\n'
        body += "    @classmethod\n"
        body += f"    def from_dict(cls, data: dict[str, Any]) -> {name}:\n"
        body += f'        """Reads a {name} from its JSON object."""\n'
        keys = ", ".join(json.dumps(p) for p in props)
        body += "        return cls(\n" + "\n".join(args) + "\n"
        body += f"            extra=extra_keys(data, ({keys}{',' if len(props) == 1 else ''})),\n"
        body += "        )\n\n\n"
    out = HEADER + '"""The request and response types of api.orbtr.ai\'s /v1 surface."""\n\n'
    out += "from __future__ import annotations\n\n"
    out += "from dataclasses import dataclass, field\n"
    out += "from typing import Any, Literal, Required, Sequence, TypedDict, Union\n\n"
    out += "from .._models import ResponseModel, extra_keys, parse_list, parse_obj\n\n"
    out += "__all__ = [\n" + "".join(f"    {json.dumps(n)},\n" for n in names) + "]\n\n\n"
    out += body
    return out.rstrip() + "\n"


def resource_tree(ops: list[dict]) -> dict[str, dict]:
    tree: dict[str, dict] = {}
    for op in ops:
        segs = op["resource"].split(".")
        for i in range(1, len(segs) + 1):
            key = ".".join(segs[:i])
            tree.setdefault(key, {"key": key, "segs": segs[:i], "ops": [], "children": []})
            if i > 1:
                parent = tree[".".join(segs[: i - 1])]
                if key not in parent["children"]:
                    parent["children"].append(key)
        tree[op["resource"]]["ops"].append(op)
    return tree


def stream_flag(contract: dict, body: str) -> str | None:
    for p, ps in contract["components"]["schemas"][body]["properties"].items():
        if ps.get("x-orbtr-stream-flag"):
            return p
    return None


METHOD_NAMES = {"countTokens": "count_tokens"}


def gen_method(contract: dict, op: dict, is_async: bool, name: str, kind: str) -> tuple[str, set[str]]:
    schemas = contract["components"]["schemas"]
    used: set[str] = set()
    sig = ["self"]
    for p in op["path_params"]:
        sig.append(f"{p['name']}: str")
    if op["path_params"]:
        sig.append("/")
    sig.append("*")
    body_items: list[str] = []
    arg_docs: list[str] = []
    flag = stream_flag(contract, op["body"]) if op["body"] else None
    if op["body"]:
        s = schemas[op["body"]]
        req = s.get("required", [])
        props = s["properties"]
        ordered = [p for p in props if p in req] + [p for p in props if p not in req]
        for p in ordered:
            if p == flag:
                continue
            ps = props[p]
            t = py_type(ps, sequence=True)
            used.update(refs_in(ps))
            sig.append(f"{p}: {t}" if p in req else f"{p}: {t} | None = None")
            body_items.append(f'"{p}": {p}')
            arg_docs.append(f"            {p}: {describe(ps, schemas)}")
        if flag and kind != "plain":
            body_items.append(f'"{flag}": True')
    query_items = []
    for q in op["query_params"]:
        sig.append(f"{q['name']}: {py_type(q['schema'])} | None = None")
        query_items.append(f'"{q["name"]}": {q["name"]}')
        arg_docs.append(f"            {q['name']}: {q['description']}")
    if op["idempotent"]:
        sig.append("idempotency_key: str | None = None")
        arg_docs.append("            idempotency_key: The Idempotency-Key; one is made when absent, and every retry sends the same key.")
    sig += [
        "extra_headers: Mapping[str, str] | None = None",
        "timeout: float | None = None",
        "max_retries: int | None = None",
    ]
    path = op["path"]
    if op["path_params"]:
        path = re.sub(r"\{(\w+)\}", lambda m: "{quote(" + m.group(1) + ", safe='')}", path)
        path_expr = f'f"{path}"'
    else:
        path_expr = json.dumps(path)
    resp = op["response"]
    used.add(resp)
    if kind == "plain":
        ret = f"list[{resp}]" if op["ndjson"] else resp
        call = "_request_ndjson" if op["ndjson"] else "_request_json"
        parse = f"{resp}.from_dict"
        summary = op["summary"]
    elif kind == "message_stream":
        ret = "AsyncMessageStream" if is_async else "MessageStream"
        call = "_message_stream"
        parse = None
        summary = op["summary"] + " The reply arrives as server-sent events."
    else:
        event = ref_name(op["stream"]["event"])
        used.add(event)
        ret = f"AsyncStream[{event}]" if is_async else f"Stream[{event}]"
        call = "_chunk_stream"
        parse = f"{event}.from_dict"
        summary = op["summary"] + " The reply arrives as server-sent events."
    route = f"{op['http']} {op['path']}" + (f" with {flag}: true" if kind != "plain" and flag else "")
    lines = [f"    {'async ' if is_async else ''}def {name}(", *[f"        {a}," for a in sig], f"    ) -> {ret}:"]
    doc = f'        """{summary}\n\n        {route}; needs the {op["scope"]} scope.\n'
    if arg_docs:
        doc += "\n        Args:\n" + "\n".join(arg_docs) + "\n"
    doc += '        """\n'
    call_args = [json.dumps(op["http"]), path_expr]
    if op["body"]:
        call_args.append("body=compact({" + ", ".join(body_items) + "})")
    if query_items:
        call_args.append("query=compact({" + ", ".join(query_items) + "})")
    if parse:
        call_args.append(f"parse={parse}")
    if op["idempotent"]:
        call_args.append("idempotent=True")
    call_args.append(
        "options=RequestOptions(extra_headers=extra_headers, timeout=timeout, max_retries=max_retries"
        + (", idempotency_key=idempotency_key" if op["idempotent"] else "")
        + ")"
    )
    ret_line = f"        return {'await ' if is_async else ''}self._client.{call}(\n" + "".join(
        f"            {a},\n" for a in call_args
    ) + "        )\n"
    return "\n".join(lines) + "\n" + doc + ret_line, used


def gen_resources(contract: dict) -> str:
    ops = operations(contract)
    tree = resource_tree(ops)
    used: set[str] = set()
    classes: dict[bool, list[str]] = {False: [], True: []}
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        for node in reversed(list(tree.values())):
            cls = prefix + pascal(node["key"])
            paths = list(dict.fromkeys(o["path"] for o in node["ops"]))
            text = f"class {cls}({'AsyncAPIResource' if is_async else 'SyncAPIResource'}):\n"
            text += f'    """The {", ".join(paths)} routes."""\n\n' if paths else f'    """The {node["key"]} resources."""\n\n'
            client_t = "AsyncAPIClient" if is_async else "SyncAPIClient"
            text += f"    def __init__(self, client: {client_t}) -> None:\n        super().__init__(client)\n"
            for child in node["children"]:
                c = tree[child]
                text += f"        self.{c['segs'][-1]} = {prefix}{pascal(child)}(client)\n"
            for op in node["ops"]:
                name = METHOD_NAMES.get(op["name"], op["name"])
                m, u = gen_method(contract, op, is_async, name, "plain")
                used |= u
                text += "\n" + m
                if op["stream"]:
                    kind = "message_stream" if op["stream"]["framing"] == "anthropic" else "chunk_stream"
                    m, u = gen_method(contract, op, is_async, "stream", kind)
                    used |= u
                    text += "\n" + m
            classes[is_async].insert(0, text)
    roots = [n for n in tree.values() if len(n["segs"]) == 1]
    out = HEADER + '"""The resources of api.orbtr.ai\'s /v1 surface, one method per operation."""\n\n'
    out += "from __future__ import annotations\n\n"
    out += "from typing import TYPE_CHECKING, Any, Literal, Mapping, Sequence, cast\nfrom urllib.parse import quote\n\n"
    out += "from .._core import AsyncAPIResource, RequestOptions, SyncAPIResource, compact\n"
    out += "from .._streaming import AsyncMessageStream, AsyncStream, MessageStream, Stream\n"
    out += "from .types import (\n" + "".join(f"    {n},\n" for n in sorted(used)) + ")\n\n"
    out += "if TYPE_CHECKING:\n    from .._core import AsyncAPIClient, SyncAPIClient\n\n\n"
    out += "\n\n".join(classes[False] + classes[True])
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        out += f"\n\nclass {prefix}Resources:\n"
        out += f'    """The API\'s resources on a{"n async" if is_async else ""} client, one per top-level path segment."""\n\n'
        for r in roots:
            out += f"    {r['key']}: {prefix}{pascal(r['key'])}\n"
        client_t = "AsyncAPIClient" if is_async else "SyncAPIClient"
        out += "\n    def _init_resources(self) -> None:\n"
        out += f'        client = cast("{client_t}", self)\n'
        for r in roots:
            out += f"        self.{r['key']} = {prefix}{pascal(r['key'])}(client)\n"
    return out


def generate(contract: dict) -> dict[str, str]:
    return {
        "src/orbtr/_generated/types.py": gen_types(contract),
        "src/orbtr/_generated/resources.py": gen_resources(contract),
    }


def main() -> int:
    contract = json.loads((ROOT / "contract" / "orbtr-v1.json").read_text())
    stale = False
    for rel, text in generate(contract).items():
        path = ROOT / rel
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        if "--check" in sys.argv:
            print(f"{rel} is not what contract/orbtr-v1.json generates; run python3 scripts/generate.py", file=sys.stderr)
            stale = True
        else:
            path.write_text(text)
            print(f"wrote {rel}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
